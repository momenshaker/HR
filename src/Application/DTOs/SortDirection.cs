namespace HR.Application.DTOs;

/// <summary>
///     Indicates how ordered results should be arranged.
/// </summary>
public enum SortDirection
{
    /// <summary>
    ///     Results are ordered from smallest to largest.
    /// </summary>
    Ascending = 0,

    /// <summary>
    ///     Results are ordered from largest to smallest.
    /// </summary>
    Descending = 1
}
